/** `date` defaults to now; the leap-year 366th day reuses day 365's thought. */
export function thoughtForToday(date: Date = new Date()): string {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const msPerDay = 24 * 60 * 60 * 1000;
  const dayOfYear = Math.floor((date.getTime() - startOfYear.getTime()) / msPerDay);
  const index = Math.min(Math.max(dayOfYear, 1), DAILY_THOUGHTS.length) - 1;
  return DAILY_THOUGHTS[index];
}
